// Rebuild collision/light data from the exact GLB shipped by the game.
// Texture decoding is unnecessary for geometry preparation in Node.
import {readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
import {Box3, Vector3, Matrix4} from 'three';
import {buildEnvironment} from '../src/model-geometry.js';
import {LAYOUT,CELL_SIZE,HEIGHT,LENGTH} from '../src/layout.js';
const modelURL=new URL('../public/models/backrooms.glb',import.meta.url);
const bytes=await readFile(modelURL),length=bytes.readUInt32LE(12);
const data=JSON.parse(bytes.subarray(20,20+length).toString());
data.buffers[0].uri=`data:application/octet-stream;base64,${bytes.subarray(28+length).toString('base64')}`;
for(const material of data.materials){
 delete material.pbrMetallicRoughness?.baseColorTexture;
 delete material.pbrMetallicRoughness?.metallicRoughnessTexture;
}
delete data.images;delete data.textures;
globalThis.ProgressEvent??=class{};
const {scene}=await new GLTFLoader().parseAsync(JSON.stringify(data),'');
const environment=buildEnvironment(scene);
environment.updateMatrixWorld(true);
const round=n=>+n.toFixed(5),lights=[];
for(const mesh of environment.children)if(mesh.material.name==='Ligts'){
 const geometry=mesh.geometry,index=geometry.index,position=geometry.attributes.position;
 const groups=[],byVertex=new Map();
 for(let i=0;i<(index?.count??position.count);i+=3){
  const points=[0,1,2].map(k=>new Vector3().fromBufferAttribute(position,index?index.getX(i+k):i+k));
  const keys=points.map(p=>p.toArray().map(round).join(','));
  const touching=[...new Set(keys.map(k=>byVertex.get(k)).filter(Boolean))];
  const group=touching[0]||{box:new Box3(),keys:new Set()};
  if(!touching.length)groups.push(group);
  for(const other of touching.slice(1)){
   group.box.union(other.box);
   for(const key of other.keys){group.keys.add(key);byVertex.set(key,group);}
   groups.splice(groups.indexOf(other),1);
  }
  points.forEach(p=>group.box.expandByPoint(p));
  keys.forEach(k=>{group.keys.add(k);byVertex.set(k,group);});
 }
 for(let i=0;i<mesh.count;i++){
  const matrix=new Matrix4();mesh.getMatrixAt(i,matrix);
  lights.push(...groups.map(g=>g.box.getCenter(new Vector3()).applyMatrix4(matrix).toArray().map(round)));
 }
}
// Every collider represents one straight source wall or one source pillar.
// Never use the bounding box of the whole instanced collection as collision.
function colliders(prefix,count){
 const parts=environment.children.filter(m=>m.name.startsWith(prefix));
 return Array.from({length:count},(_,i)=>{
  const box=new Box3();
  for(const part of parts){
   const matrix=new Matrix4();part.getMatrixAt(i,matrix);
   box.union(part.geometry.boundingBox.clone().applyMatrix4(matrix));
  }
  const center=box.getCenter(new Vector3()),size=box.getSize(new Vector3());
  return{x:round(center.x),z:round(center.z),w:round(size.x),d:round(size.z)};
 });
}
const walls=colliders('wall_',LAYOUT.walls.length);
const pillars=colliders('pillar_',LAYOUT.pillars.length);
const sourceTriangles=environment.children.reduce((sum,m)=>sum+(m.geometry.index?.count??m.geometry.attributes.position.count)/3*m.count,0);
const result={source:'backrooms.glb',sha256:createHash('sha256').update(bytes).digest('hex'),cellSize:CELL_SIZE,height:HEIGHT,length:LENGTH,walls,pillars,lights,rooms:LAYOUT.rooms.length,sourceTriangles};
const outputURL=new URL('../src/model-data.js',import.meta.url);
const output=`// Generated by scripts/prepare-map.mjs; do not edit by hand.\nexport default ${JSON.stringify(result)};\n`;
if(process.argv.includes('--check')){
 if((await readFile(outputURL,'utf8')).replace(/\r\n/g,'\n')!==output)throw new Error('Model data is stale. Run npm run prepare-map.');
}else await writeFile(outputURL,output);
console.log(`Prepared ${walls.length} modular walls, ${pillars.length} pillars, ${lights.length} fixtures; ${LENGTH.toFixed(1)} m square.`);
